import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
import { parseCsv } from "../docs/src/transport/csv.js";
const base="http://127.0.0.1:8765";
await mkdir("logs",{recursive:true});
const browser=await chromium.launch();
const context=await browser.newContext();
await context.tracing.start({screenshots:true,snapshots:true});
const page=await context.newPage();
let step="startup";
const errors=[];
page.on("pageerror",e=>{errors.push(e.message);console.error(e.stack)});
page.on("console",m=>console.log("browser",m.type(),m.text()));
const row=()=>page.locator("#patients tr").filter({hasText:"Test Patient One"});
const waitText=async(locator,value)=>{await locator.filter({hasText:value}).waitFor({state:"visible"});};
const open=async()=>{await row().click();await page.locator("#editor").waitFor({state:"visible"});};
const save=async()=>{await page.locator("#add").click();await page.locator("#editor").waitFor({state:"hidden"});};
try{
 for(let i=0;i<30;i++){try{if((await fetch(base+"/api/health")).ok)break;}catch{}await new Promise(r=>setTimeout(r,1000));}
 await page.goto(base);
 await row().waitFor();
 assert.equal(await page.locator("#patients tr").count(),2);
 step="search exact text ID";
 await page.locator("#search").fill("000000001");
 assert.equal(await page.locator("#patients tr").count(),1);
 await page.locator("#search").fill("");
 step="create signed discharge and family notice";
 await open();
 await waitText(page.locator("#modalTitle"),"000000001");
 await page.locator("#dischargeDate").fill("01/12/2026");
 await page.locator("#noticeDate").fill("28/11/2026 10:00");
 await page.locator("#recipient").fill("בת");
 await page.locator("#messenger").fill("אחות");
 await page.locator("#remarks").fill("תיעוד ראשון");
 await page.locator("#signer").fill("");
 await page.locator("#add").click();
 await waitText(page.locator("#formError"),"שם החותם");
 await page.locator("#signer").fill("Test Doctor");
 await save();
 await waitText(row(),"תיעוד ראשון");
 await waitText(row(),"בת");
 step="change discharge date";
 await open();
 await page.locator("#dischargeDate").fill("03/12/2026");
 await page.locator("#remarks").fill("תאריך חדש");
 await save();
 await waitText(row(),"תאריך חדש");
 await waitText(row(),"לא נמסר");
 step="cancel discharge";
 await open();
 await page.locator("#cancelDischarge").check();
 await page.locator("#remarks").fill("ביטול");
 await save();
 await waitText(row(),"בוטל");
 step="reload and verify signed history";
 await page.reload();
 await waitText(row(),"בוטל");
 await open();
 await page.locator("details.history summary").click();
 assert.equal(await page.locator("#history .history-record").count(),2);
 await waitText(page.locator("#history"),"תיעוד ראשון");
 await waitText(page.locator("#history"),"תאריך חדש");
 await waitText(page.locator("#latest"),"בוטל");
 await page.locator("#closeTop").click();
 step="disconnect and block saving";
 await page.route("**/api/heartbeat",route=>route.abort());
 await page.evaluate(()=>window.dispatchEvent(new Event("online")));
 await page.locator("#mode").filter({hasText:"נותק"}).waitFor({timeout:25000});
 await open();
 await page.locator("#dischargeDate").fill("05/12/2026");
 await page.locator("#signer").fill("Test Doctor");
 await page.locator("#add").click();
 await waitText(page.locator("#formError"),"אין חיבור");
 await page.locator("#closeTop").click();
 step="reconnect and reload persisted state";
 await page.unroute("**/api/heartbeat");
 await page.evaluate(()=>window.dispatchEvent(new Event("online")));
 await page.locator("#mode").filter({hasText:"מחובר לשרת המקומי"}).waitFor({timeout:25000});
 await waitText(row(),"בוטל");
 step="verify physical CSV";
 const records=parseCsv(await readFile("server/ci-records.csv","utf8"));
 assert.equal(records.length,3);
 assert.deepEqual(records.map(r=>r.PatientID),Array(3).fill("000000001"));
 assert.deepEqual(records.map(r=>r.DischargeDate),["2026-12-01","2026-12-03",""]);
 assert.equal(records[0].Recipient,"בת");
 assert.equal(records[1].Recipient,"");
 assert.deepEqual(errors,[]);
 console.log("PASS: browser workflow and persisted history");
}catch(e){
 console.error("FAILED STEP:",step,e.stack);
 console.error("Form error:",await page.locator("#formError").textContent().catch(()=> ""));
 await page.screenshot({path:"logs/browser-failure.png",fullPage:true}).catch(()=>{});
 throw e;
}finally{
 await context.tracing.stop({path:"logs/browser-trace.zip"});
 await browser.close();
}
